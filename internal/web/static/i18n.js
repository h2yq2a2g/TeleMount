let currentLang = (typeof localStorage !== 'undefined' && localStorage.getItem('tm_lang') === 'vi') ? 'vi' : 'en';

function normalizeLang(lang) {
  return String(lang || '').toLowerCase() === 'vi' ? 'vi' : 'en';
}

function getLang() {
  return currentLang;
}

function t(key, vars) {
  const dict = I18N[currentLang] || I18N.en;
  let str = dict[key] !== undefined ? dict[key] : (I18N.en[key] !== undefined ? I18N.en[key] : key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, String(v ?? ''));
    }
  }
  return str;
}

function applyI18n(lang) {
  if (lang) {
    currentLang = normalizeLang(lang);
    try { localStorage.setItem('tm_lang', currentLang); } catch (_) {}
  }
  document.documentElement.lang = currentLang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('.lang-btn[data-lang]').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });
}
